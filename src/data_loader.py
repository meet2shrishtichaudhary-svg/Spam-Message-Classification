"""Dataset loading, validation, and cleaning module for Spam Message Classification.

Handles Kaggle SMS Spam Collection format (v1/v2 columns, Latin-1 encoding),
cleans duplicate/empty rows, normalizes labels (ham -> 0, spam -> 1),
and displays dataset distributions.
"""

import sys
from pathlib import Path
from typing import Dict, Optional, Tuple, Union

# Ensure project root is on sys.path for standalone script execution
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import pandas as pd


def load_dataset(
    filepath: Union[str, Path] = "dataset/spam.csv",
    verbose: bool = True
) -> pd.DataFrame:
    """Load, clean, and validate the SMS Spam Collection dataset.

    Parameters
    ----------
    filepath : str or Path
        Path to the CSV or TSV dataset file.
    verbose : bool
        If True, prints summary statistics of the loaded dataset.

    Returns
    -------
    pd.DataFrame
        Cleaned DataFrame with exactly two columns:
        - 'label' (int: 0 for Ham, 1 for Spam)
        - 'message' (str: Raw message text)

    Raises
    ------
    FileNotFoundError
        If the specified file path does not exist.
    ValueError
        If required columns are missing or label values cannot be parsed.
    """
    path = Path(filepath)
    if not path.is_file():
        raise FileNotFoundError(
            f"Dataset not found at '{filepath}'. Please place 'spam.csv' inside the "
            f"'dataset/' folder. Expected format: Kaggle SMS Spam Collection."
        )

    # 1. Attempt reading with utf-8, fallback to latin-1 (standard for Kaggle SMS dataset)
    df = None
    encodings_to_try = ["utf-8", "latin-1", "cp1252"]
    for enc in encodings_to_try:
        try:
            # Check if file might be tab-separated or comma-separated
            sep = "\t" if path.suffix.lower() == ".tsv" else ","
            df = pd.read_csv(path, encoding=enc, sep=sep)
            break
        except UnicodeDecodeError:
            continue
        except Exception as e:
            raise ValueError(f"Error reading dataset file at '{filepath}': {e}") from e

    if df is None:
        raise ValueError(
            f"Unable to decode '{filepath}' using supported encodings: {encodings_to_try}"
        )

    raw_shape = df.shape

    # 2. Drop unnecessary 'Unnamed:*' columns commonly generated by trailing commas
    unnamed_cols = [col for col in df.columns if str(col).lower().startswith("unnamed")]
    if unnamed_cols:
        df = df.drop(columns=unnamed_cols)

    # 3. Identify and normalize column names to 'label' and 'message'
    col_mapping = {}
    lower_cols = {str(col).strip().lower(): col for col in df.columns}

    # Label column candidates
    if "v1" in lower_cols:
        col_mapping[lower_cols["v1"]] = "label"
    elif "label" in lower_cols:
        col_mapping[lower_cols["label"]] = "label"
    elif "category" in lower_cols:
        col_mapping[lower_cols["category"]] = "label"
    elif "class" in lower_cols:
        col_mapping[lower_cols["class"]] = "label"

    # Message column candidates
    if "v2" in lower_cols:
        col_mapping[lower_cols["v2"]] = "message"
    elif "message" in lower_cols:
        col_mapping[lower_cols["message"]] = "message"
    elif "text" in lower_cols:
        col_mapping[lower_cols["text"]] = "message"
    elif "sms" in lower_cols:
        col_mapping[lower_cols["sms"]] = "message"

    if "label" not in col_mapping.values() or "message" not in col_mapping.values():
        raise ValueError(
            f"Unsupported dataset format in '{filepath}'. "
            f"Found columns: {list(df.columns)}. "
            f"Expected columns containing label ('v1', 'label', 'category') "
            f"and message ('v2', 'message', 'text')."
        )

    df = df.rename(columns=col_mapping)
    df = df[["label", "message"]].copy()

    # 4. Remove missing or empty messages
    df = df.dropna(subset=["label", "message"])
    # Ensure message is string and strip whitespace
    df["message"] = df["message"].astype(str)
    df = df[df["message"].str.strip().str.len() > 0]

    # 5. Deduplication strategy:
    # Documented strategy: Keep first occurrence of duplicate messages.
    # Spam datasets often contain duplicate promotional broadcasts. Keeping the
    # first occurrence ensures diverse representation and prevents the exact same
    # message from leaking across train/test splits.
    duplicates_count = int(df.duplicated(subset=["message"]).sum())
    df = df.drop_duplicates(subset=["message"], keep="first").copy()

    # 6. Normalize and map labels to integers (0: ham, 1: spam)
    def map_label(val) -> int:
        if isinstance(val, (int, float)) and val in (0, 1):
            return int(val)
        val_str = str(val).strip().lower()
        if val_str in ("ham", "0", "legit", "normal", "not spam"):
            return 0
        if val_str in ("spam", "1", "fraud"):
            return 1
        raise ValueError(f"Unrecognized label value: '{val}'. Expected 'ham' or 'spam'.")

    df["label"] = df["label"].apply(map_label).astype(int)

    # Reset index for clean sequential ordering
    df = df.reset_index(drop=True)

    if df.empty:
        raise ValueError(f"Dataset '{filepath}' is empty after cleaning.")

    if verbose:
        print_dataset_summary(df, raw_shape=raw_shape, duplicates_removed=duplicates_count)

    return df


def get_dataset_summary(df: pd.DataFrame) -> Dict[str, Union[int, float]]:
    """Compute summary metrics and class distribution of the dataset."""
    total = len(df)
    ham_count = int((df["label"] == 0).sum())
    spam_count = int((df["label"] == 1).sum())
    ham_pct = (ham_count / total * 100) if total > 0 else 0.0
    spam_pct = (spam_count / total * 100) if total > 0 else 0.0

    return {
        "total_messages": total,
        "ham_count": ham_count,
        "spam_count": spam_count,
        "ham_percentage": round(ham_pct, 2),
        "spam_percentage": round(spam_pct, 2),
    }


def print_dataset_summary(
    df: pd.DataFrame,
    raw_shape: Optional[Tuple[int, int]] = None,
    duplicates_removed: int = 0
) -> None:
    """Print a clean formatted dataset summary to standard output."""
    summary = get_dataset_summary(df)
    print("=" * 60)
    print("       SMS SPAM COLLECTION - DATASET SUMMARY")
    print("=" * 60)
    if raw_shape:
        print(f"Raw dataset shape      : {raw_shape[0]} rows x {raw_shape[1]} columns")
        print(f"Duplicates removed     : {duplicates_removed}")
    print(f"Cleaned dataset shape  : {df.shape[0]} rows x {df.shape[1]} columns")
    print(f"Total valid messages   : {summary['total_messages']:,}")
    print(f"  - Ham (Legitimate)   : {summary['ham_count']:,} ({summary['ham_percentage']}%) [Label: 0]")
    print(f"  - Spam (Unwanted)    : {summary['spam_count']:,} ({summary['spam_percentage']}%) [Label: 1]")
    print("=" * 60)


